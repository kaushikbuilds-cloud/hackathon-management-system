/**
 * Generates the animated app-open icon (Android 12+ splash) from the traced
 * HackGround OS "H": the left bar rises in, the right bar drops in, the bridge
 * draws across, then the mark gently pulses until the site has loaded.
 *   node scripts/splash-animation.cjs            → res/drawable/splash_animated.xml
 *   node scripts/splash-animation.cjs preview.gif → also an animated preview (needs sharp)
 */
const fs = require("fs");
const path = require("path");

// Shapes in a 600×600 box (traced from the logo).
const SHAPES = {
  left: { d: "M40,150 L228,30 L228,212 L80,300 L80,528 L40,500 Z", g: [40, 30, 228, 528, [[0, "#F1F0FB"], [0.6, "#C9C3F2"], [1, "#8B6CF0"]]] },
  right: { d: "M370,150 L555,45 L555,462 L370,578 Z", g: [370, 45, 555, 578, [[0, "#9F6BF7"], [0.55, "#6D4CF0"], [1, "#4338CA"]]] },
  bridge: { d: "M80,300 L232,212 L425,322 L425,432 L232,322 L130,382 L130,500 L80,528 Z", g: [80, 212, 425, 432, [[0, "#E4E1F8"], [0.5, "#B69CF5"], [1, "#8B5CF6"]]] },
};
// Intro (ms): [start, end] for each piece; then a pulse loop.
const INTRO = 850, PULSE_START = 900, PULSE_HALF = 700, PULSE_SCALE = 1.05;
const T = { left: [0, 450], right: [150, 600], bridge: [400, 850] };
const OFFSET = { left: 40, right: -40 };

// Android 12+ splash icon: 288dp box, content inside the central 192dp circle.
const BOX = 288, SCALE = 0.26, SHIFT = BOX / 2 - 300 * SCALE;

const gradientXml = ([x1, y1, x2, y2, stops]) =>
  `<gradient android:type="linear" android:startX="${x1}" android:startY="${y1}" android:endX="${x2}" android:endY="${y2}">${stops
    .map(([o, c]) => `<item android:offset="${o}" android:color="${c}"/>`).join("")}</gradient>`;

function avd() {
  const f = (ms) => +(ms / INTRO).toFixed(3);
  const kf = (prop, pairs) => `<propertyValuesHolder android:propertyName="${prop}">${pairs
    .map(([ms, v]) => `<keyframe android:fraction="${f(ms)}" android:value="${v}" android:valueType="floatType" android:interpolator="@android:interpolator/fast_out_slow_in"/>`).join("")}</propertyValuesHolder>`;
  const target = (name, holders) => `  <target android:name="${name}"><aapt:attr name="android:animation"><objectAnimator android:duration="${INTRO}">${holders.join("")}</objectAnimator></aapt:attr></target>`;
  const fade = (name) => {
    const [a, b] = T[name];
    const pairs = [[0, 0], ...(a > 0 ? [[a, 0]] : []), [b, 1], ...(b < INTRO ? [[INTRO, 1]] : [])];
    return target(`${name}Path`, [kf("fillAlpha", pairs), kf("strokeAlpha", pairs)]);
  };
  const slide = (name) => {
    const [a, b] = T[name], o = OFFSET[name];
    return target(name, [kf("translateY", [[0, o], ...(a > 0 ? [[a, o]] : []), [b, 0], [INTRO, 0]])]);
  };
  const grow = () => {
    const [a, b] = T.bridge;
    return target("bridge", [kf("scaleX", [[0, 0], [a, 0], [b, 1]])]);
  };
  const piece = (name, extra = "") => {
    const s = SHAPES[name];
    return `        <group android:name="${name}"${extra}>
          <path android:name="${name}Path" android:pathData="${s.d}" android:strokeWidth="14" android:strokeLineJoin="round">
            <aapt:attr name="android:fillColor">${gradientXml(s.g)}</aapt:attr>
            <aapt:attr name="android:strokeColor">${gradientXml(s.g)}</aapt:attr>
          </path>
        </group>`;
  };
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by mobile/scripts/splash-animation.cjs: the app-open animation (Android 12+). -->
<animated-vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt">
  <aapt:attr name="android:drawable">
    <vector android:width="${BOX}dp" android:height="${BOX}dp" android:viewportWidth="${BOX}" android:viewportHeight="${BOX}">
      <group android:translateX="${SHIFT}" android:translateY="${SHIFT}" android:scaleX="${SCALE}" android:scaleY="${SCALE}">
      <group android:name="pulse" android:pivotX="300" android:pivotY="300">
${piece("left")}
${piece("right")}
${piece("bridge", ' android:pivotX="80" android:pivotY="300"')}
      </group>
      </group>
    </vector>
  </aapt:attr>
${slide("left")}
${fade("left")}
${slide("right")}
${fade("right")}
${grow()}
${fade("bridge")}
  <target android:name="pulse"><aapt:attr name="android:animation"><objectAnimator android:startOffset="${PULSE_START}" android:duration="${PULSE_HALF}" android:repeatCount="infinite" android:repeatMode="reverse" android:interpolator="@android:interpolator/fast_out_slow_in"><propertyValuesHolder android:propertyName="scaleX" android:valueFrom="1" android:valueTo="${PULSE_SCALE}" android:valueType="floatType"/><propertyValuesHolder android:propertyName="scaleY" android:valueFrom="1" android:valueTo="${PULSE_SCALE}" android:valueType="floatType"/></objectAnimator></aapt:attr></target>
</animated-vector>
`;
}

// ---- preview (same timings, rendered frame by frame) ----
const ease = (t) => { t = Math.min(1, Math.max(0, t)); return t < 0.5 ? 4 * t * t * t : 1 - Math.pow(-2 * t + 2, 3) / 2; };
const prog = (ms, [a, b]) => ease((ms - a) / (b - a));
function frameSvg(ms, size) {
  const pulse = ms < PULSE_START ? 1 : 1 + (PULSE_SCALE - 1) * ease(1 - Math.abs(((ms - PULSE_START) / PULSE_HALF) % 2 - 1));
  const defs = Object.entries(SHAPES).map(([n, s]) => `<linearGradient id="${n}" gradientUnits="userSpaceOnUse" x1="${s.g[0]}" y1="${s.g[1]}" x2="${s.g[2]}" y2="${s.g[3]}">${s.g[4].map(([o, c]) => `<stop offset="${o}" stop-color="${c}"/>`).join("")}</linearGradient>`).join("");
  const shape = (n, tf) => { const p = prog(ms, T[n]); return `<g transform="${tf(p)}" opacity="${p}"><path d="${SHAPES[n].d}" fill="url(#${n})" stroke="url(#${n})" stroke-width="14" stroke-linejoin="round"/></g>`; };
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size * 1.6}" viewBox="0 0 ${BOX} ${BOX * 1.6}"><defs>${defs}</defs>
<rect width="100%" height="100%" fill="#0D0F1C"/>
<g transform="translate(${SHIFT} ${SHIFT + BOX * 0.3}) scale(${SCALE})"><g transform="translate(300 300) scale(${pulse}) translate(-300 -300)">
${shape("left", (p) => `translate(0 ${OFFSET.left * (1 - p)})`)}
${shape("right", (p) => `translate(0 ${OFFSET.right * (1 - p)})`)}
${shape("bridge", (p) => `translate(80 300) scale(${Math.max(p, 0.001)} 1) translate(-80 -300)`)}
</g></g></svg>`;
}

const out = path.join(__dirname, "../android/app/src/main/res/drawable/splash_animated.xml");
fs.writeFileSync(out, avd());
console.log("wrote", path.relative(process.cwd(), out));
const gif = process.argv[2];
if (gif) {
  const sharp = require(require.resolve("sharp", { paths: [process.cwd(), path.join(__dirname, "../..")] }));
  (async () => {
    const fps = 25, total = PULSE_START + 4 * PULSE_HALF;
    const frames = [];
    for (let ms = 0; ms <= total; ms += 1000 / fps) frames.push(await sharp(Buffer.from(frameSvg(ms, 240))).png().toBuffer());
    await sharp(frames, { join: { animated: true } }).gif({ delay: Array(frames.length).fill(1000 / fps), loop: 0 }).toFile(gif);
    console.log("wrote", gif, frames.length, "frames");
  })();
}
