// Concatenates all migrations into supabase/dist/setup.sql for pasting into the
// Supabase dashboard SQL editor (when the Supabase CLI is not available).
// Pass --with-seed to append the DEVELOPMENT seed data.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";

const dir = "supabase/migrations";
const parts = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort()
  .map((f) => `-- >>> ${dir}/${f}\n${readFileSync(`${dir}/${f}`, "utf8")}`);
if (process.argv.includes("--with-seed")) parts.push(`-- >>> supabase/seed.sql (DEVELOPMENT DATA)\n${readFileSync("supabase/seed.sql", "utf8")}`);
mkdirSync("supabase/dist", { recursive: true });
writeFileSync("supabase/dist/setup.sql", `-- Generated by npm run db:bundle. Run once on an EMPTY project.\nbegin;\n\n${parts.join("\n\n")}\n\ncommit;\n`);
console.log("Wrote supabase/dist/setup.sql");
